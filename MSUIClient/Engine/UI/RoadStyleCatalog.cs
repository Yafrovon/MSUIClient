using System.Numerics;
using System.Text.Json.Nodes;

namespace MSUIClient.Engine.UI;

/// <summary>A road's dirt verge: a second ground texture laid first, <see cref="Extra"/> yards wider on each side.</summary>
public sealed record RoadShoulderStyle(string Texture, float Extra, float SoftEdge, float Strength);

/// <summary>
/// One road look measured from the stock world: which texture, how wide, how soft its edge, how ragged and patchy, and
/// which shoulder runs under it. <see cref="Kind"/>: "road" (a road-named texture's bands in that zone), "trail" (a plain
/// dirt that forms road-like bands there), "surface" (a paving texture never seen as a band).
/// </summary>
public sealed record RoadStyle(string Id, string Name, string Kind, int Map, string Zone, string Texture, float Width, float SoftEdge,
    float Strength, float Ragged, float Patchy, RoadShoulderStyle? Shoulder, string? Ground, double MeasuredLength, Vector3? Example);

/// <summary>
/// The World Builder's road styles: <c>Data/road-styles.json</c>, generated by <c>tools/road-survey</c> from every stock
/// ADT (shared_docs/ROAD_STYLES.md lists them all with how each number was measured). Embedded in the client; read once.
/// </summary>
public static class RoadStyleCatalog
{
    public const string Resource = "MSUIClient.Data.road-styles.json";
    private static IReadOnlyList<RoadStyle>? _styles;

    public static IReadOnlyList<RoadStyle> Load()
    {
        if (_styles is not null) return _styles;
        var list = new List<RoadStyle>();
        try
        {
            using var stream = typeof(RoadStyleCatalog).Assembly.GetManifestResourceStream(Resource);
            if (stream is not null && JsonNode.Parse(stream)?["styles"] is JsonArray styles)
                foreach (var node in styles.OfType<JsonObject>())
                    if (Parse(node) is { } style) list.Add(style);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"[wb] road styles could not be read: {ex.Message}");
        }
        return _styles = list;
    }

    /// <summary>The style whose texture the ground shows most at a point. <paramref name="weights"/>: texture -> visible
    /// weight there. Ties go to the style on <paramref name="map"/> whose measured example lies nearest.</summary>
    public static RoadStyle? Match(IReadOnlyDictionary<string, float> weights, int map, Vector2 at)
    {
        RoadStyle? best = null;
        float bestScore = 0f;
        foreach (var style in Load())
        {
            if (!weights.TryGetValue(style.Texture, out float w) || w < 0.2f) continue;
            float near = style.Map == map && style.Example is { } ex ? 1f / (1f + Vector2.Distance(new(ex.X, ex.Y), at) / 2000f) : 0f;
            float score = w * 4f + near + (style.Kind == "road" ? 0.25f : 0f);
            if (score > bestScore) { bestScore = score; best = style; }
        }
        return best;
    }

    private static RoadStyle? Parse(JsonObject o)
    {
        string? texture = o["texture"]?.ToString();
        if (string.IsNullOrEmpty(texture)) return null;
        RoadShoulderStyle? shoulder = o["shoulder"] is JsonObject s && s["texture"]?.ToString() is { Length: > 0 } st
            ? new RoadShoulderStyle(st, F(s["extra"], 2f), F(s["softEdge"], 2f), F(s["strength"], 1f))
            : null;
        Vector3? example = o["example"] is JsonArray e && e.Count >= 3 ? new Vector3(F(e[0], 0), F(e[1], 0), F(e[2], 0)) : null;
        return new RoadStyle((string?)o["id"] ?? texture, (string?)o["name"] ?? texture, (string?)o["kind"] ?? "road", (int?)o["map"] ?? -1,
            (string?)o["zone"] ?? "", texture, F(o["width"], 5f), F(o["softEdge"], 2f), F(o["strength"], 1f), F(o["ragged"], 0f),
            F(o["patchy"], 0f), shoulder, (string?)o["ground"], (double?)o["measuredLength"] ?? 0, example);
    }

    private static float F(JsonNode? n, float fallback)
    {
        try { return n is null ? fallback : (float)(double)n; }
        catch { return fallback; }
    }
}
