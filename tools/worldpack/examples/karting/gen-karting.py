def box_rows(sql):
    """SELECT on the box's world DB -> list of dicts (strings; NULL -> None)."""
    out = subprocess.run(["ssh", "-o", "BatchMode=yes", "wowvmangos@192.168.0.2",
                          f"mysql -umangos -pmangos mangos --batch -e \"{sql}\""],
                         capture_output=True, text=True, check=True).stdout
    lines = [l for l in out.split("\n") if l]
    head = lines[0].split("\t")
    return [{k: (None if v == "NULL" else v) for k, v in zip(head, l.split("\t"))} for l in lines[1:]]


def typed(row):
    """Numbers as JSON numbers so the dbrow writer binds them as numbers."""
    out = {}
    for k, v in row.items():
        if v is None:
            out[k] = None
            continue
        try:
            out[k] = int(v)
        except ValueError:
            try:
                out[k] = float(v)
            except ValueError:
                out[k] = v
    return out


def height(mapid, x, y):
    url = f"{WEB}/WorldMap/GetHeight?map={mapid}&x={x}&y={y}"
    z = json.load(urllib.request.urlopen(url, timeout=30)).get("z")
    if z is None:
        raise SystemExit(f"no terrain height at map {mapid} ({x}, {y})")
    return float(z)


def leg_z(leg, x, y):
    """Ground height for a point on LEG: a route written [x, y, z] (rooftops, city walls - surfaces the server's
    terrain-only height query cannot see) is interpolated along its nearest segment; otherwise the terrain."""
    route = leg["route"]
    if not all(len(q) > 2 for q in route):
        return height(leg["map"], x, y)
    best = None
    for k in range(len(route) - 1):
        (ax, ay, az), (bx, by, bz) = route[k][:3], route[k + 1][:3]
        dx, dy = bx - ax, by - ay
        t = max(0.0, min(1.0, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy or 1e-9)))
        d = math.dist((x, y), (ax + dx * t, ay + dy * t))
        if best is None or d < best[0]:
            best = (d, az + (bz - az) * t)
    return best[1]


def row(table, body):
    return {"kind": f"dbrow:{table}", "body": body}


def dbc(name, rid, clone, fields):
    return {"kind": f"dbc:{name}", "key": str(rid), "body": {"cloneFrom": clone, "fields": fields}}


def length(route):
    return sum(math.dist(route[i][:2], route[i + 1][:2]) for i in range(len(route) - 1))


