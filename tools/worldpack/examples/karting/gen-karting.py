def portal_items(course, teleport, go_template):
    items = []
    legs = course["legs"]
    for i, leg in enumerate(legs):
        p = leg.get("portal")
        if not p:
            continue
        dest = legs[p["to"]]
        ax, ay, az, ao = dest["arrive"]
        az = (az if az else leg_z(dest, ax, ay)) + 0.5
        pz = p.get("z")
        if pz is None:
            pz = leg_z(leg, p["x"], p["y"])
        spell = PORTAL_SPELL_BASE + i
        entry = PORTAL_TEMPLATE_BASE + i
        guid = PORTAL_GUID_BASE + i
        name = p.get("name") or f"Portal to {dest['name']}"
        t = dict(teleport)
        t.update({"entry": spell, "build": 5875, "name": f"Kart Portal: {dest['name']}"})
        items.append(row("spell_template", t))
        items.append(dbc("Spell", spell, PORTAL_SOURCE_SPELL, {str(DBC_NAME): t["name"]}))
        items.append(row("spell_target_position", {
            "id": spell, "target_map": dest["map"], "target_position_x": ax, "target_position_y": ay,
            "target_position_z": round(az, 2), "target_orientation": ao, "build_min": 0, "build_max": 5875}))
        g = dict(go_template)
        g.update({"entry": entry, "patch": 0, "name": name, "faction": 35,
                  "data0": spell, "data1": 0, "data2": 0, "data3": 1, "data4": 1})
        items.append(row("gameobject_template", g))
        o = float(p.get("o", 0.0))
        items.append(row("gameobject", {
            "guid": guid, "id": entry, "map": leg["map"], "position_x": p["x"], "position_y": p["y"],
            "position_z": round(pz, 2), "orientation": o, "rotation0": 0, "rotation1": 0,
            "rotation2": round(math.sin(o / 2), 6), "rotation3": round(math.cos(o / 2), 6),
            "spawntimesecsmin": 0, "spawntimesecsmax": 0, "animprogress": 100, "state": 1, "spawn_flags": 0,
            "visibility_mod": 0, "patch_min": 0, "patch_max": 10}))
    return items


# -- laid track ----------------------------------------------------------------------------------

def track_items(course):
    """Laid track: a leg's "ramp" is a World Builder graded path (doc kind "path") - the ground takes the path's
    height within half the width and its short falloff makes the lip a kart jumps off."""
    items = []
    for leg in course["legs"]:
        r = leg.get("ramp")
        if r:
            items.append({"kind": "path", "key": r["name"], "body": {
                "map": leg["map"], "points": r["points"], "width": r["width"], "falloff": r["falloff"], "clear": True}})
        # A cleared lane: props (trees, roots, boulders) standing in the racing line are removed and the ground
        # stays exactly as it is ("grade": false) - `kart-course.py props` lists them (a kart stops dead on a trunk).
        for lane in leg.get("lanes", []):
            route = lane["points"] if "points" in lane else leg["route"][lane["from"]:lane["to"] + 1]
            pts = []
            for k in range(len(route) - 1):
                (ax, ay), (bx, by) = route[k][:2], route[k + 1][:2]
                n = max(1, int(math.dist((ax, ay), (bx, by)) // 6))
                pts += [(ax + (bx - ax) * t / n, ay + (by - ay) * t / n) for t in range(n)]
            pts.append(tuple(route[-1][:2]))
            items.append({"kind": "path", "key": lane["name"], "body": {
                "map": leg["map"], "points": [[round(x, 1), round(y, 1), round(height(leg["map"], x, y), 2)] for x, y in pts],
                "width": lane.get("width", 8), "falloff": lane.get("falloff", 2), "clear": True, "grade": False}})
    return items


# -- the race course (Core SuiKartingRace.cpp reads it) ------------------------------------------

COURSE_KEY = "azeroth"
TELE_BASE = 7400          # game_tele ids of the course (pack rule: >= 7000)


def box_points(course):
    """Item box rows: four boxes across the road at fractions of each leg's route (leg "boxes": [f, ...])."""
    out = []
    for leg in course["legs"]:
        route = [p[:2] for p in leg["route"]]
        total = length(route)
        for f in leg.get("boxes", [0.4, 0.75]):
            want, walked = total * f, 0.0
            for k in range(len(route) - 1):
                seg = math.dist(route[k], route[k + 1])
                if walked + seg >= want:
                    t = (want - walked) / seg
                    x = route[k][0] + (route[k + 1][0] - route[k][0]) * t
                    y = route[k][1] + (route[k + 1][1] - route[k][1]) * t
                    o = math.atan2(route[k + 1][1] - route[k][1], route[k + 1][0] - route[k][0])
                    spacing = leg.get("boxSpacing", 3.5)
                    for i in range(4):
                        off = (i - 1.5) * spacing
                        out.append((leg, x - math.sin(o) * off, y + math.cos(o) * off, o))
                    break
                walked += seg
    return out


def course_items(course):
    """The race the Core runs (SuiKarting RaceManager) reads its course from these game_tele rows - pack rows, so
    the race exists only while the pack is enabled, and every point is also a `.tele kart:...` for testing:
      kart:<course>:meta:laps=<n>       at the start line
      kart:<course>:grid:<nn>           start slots (orientation = facing)
      kart:<course>:cp:<nn>:r<radius>   checkpoints in lap order; cp 00 is the start/finish line
      kart:<course>:box:<nn>            item boxes (MK64 items, Phase 5)
      kart:<course>:portal:<ll>:<entry> the leg's portal gameobject (bots use it; racers get its destination to prewarm)
      kart:<course>:line:<ll>:<nn>      each leg's racing line (bots drive it), its last point at the leg's portal
    """
    rows, tid = [], TELE_BASE
    start = course["start"]

    def tele(name, mapid, x, y, o=0.0, leg=None):
        nonlocal tid
        z = (leg_z(leg, x, y) if leg is not None else height(mapid, x, y)) + 0.5
        rows.append(row("game_tele", {"id": tid, "position_x": x, "position_y": y, "position_z": round(z, 2),
                                      "orientation": round(o, 4), "map": mapid, "name": f"kart:{COURSE_KEY}:{name}"}))
        tid += 1

    lx, ly = start["line"]
    tele(f"meta:laps={course['laps']}", start["map"], lx, ly, start["facing"])
    for i, (x, y) in enumerate(start["grid"]):
        tele(f"grid:{i:02d}", start["map"], x, y, start["facing"])
    cps = [(start["map"], lx, ly, 45, None)]
    for leg in course["legs"]:
        cps += [(leg["map"], c[0], c[1], c[2] if len(c) > 2 else 45, leg) for c in leg.get("checkpoints", [])
                if math.dist(c[:2], (lx, ly)) > 1]
    for i, (m, x, y, r, leg) in enumerate(cps):
        tele(f"cp:{i:02d}:r{int(r)}", m, x, y, leg=leg)
    for i, (leg, x, y, o) in enumerate(box_points(course)):
        tele(f"box:{i:02d}", leg["map"], round(x, 1), round(y, 1), o, leg=leg)
    for li, leg in enumerate(course["legs"]):
        if leg.get("portal"):
            p = leg["portal"]
            tele(f"portal:{li:02d}:{PORTAL_TEMPLATE_BASE + li}", leg["map"], p["x"], p["y"], p.get("o", 0.0), leg=leg)
        pts = [list(p[:2]) for p in leg["route"]]
        if leg.get("portal"):
            pts.append([leg["portal"]["x"], leg["portal"]["y"]])
        for k, (x, y) in enumerate(pts):
            tele(f"line:{li:02d}:{k:02d}", leg["map"], x, y, leg=leg)
    return rows


