def post(path, body):
    req = urllib.request.Request(f"{WEB}{path}", data=json.dumps(body).encode(),
                                 headers={"Content-Type": "application/json"}, method="POST")
    return json.load(urllib.request.urlopen(req, timeout=300))


def pack_id():
    packs = json.load(urllib.request.urlopen(f"{WEB}/WorldPacks/Packs", timeout=60))["packs"]
    for p in packs:
        if p["packKey"] == PACK_KEY:
            return p["id"]
    r = post("/WorldPacks/CreatePack", {"key": PACK_KEY, "name": "WoW Karting",
                                         "description": "Racer karts, public Real Portals and the Azeroth Circuit (shared_docs/WOW_KARTING.md)",
                                         "operator": "gen-karting"})
    return r["pack"]["id"] if isinstance(r.get("pack"), dict) else r["pack"]


